def frames_en():
    out = ['# Generated by tools/mkcorpus_frames_en.py: English frame generator coverage.',
           '#stages 1', '#lang en']
    texts = EN + EXTRA_TEXT
    for v in range(20):
        out.append(f'#voice {v}')
        out += [texts[(v * 3 + k) % len(texts)] for k in range(3)]
    out.append('#voice 0')
    i = 0
    for key, values in mkcorpus.SWEEPS:
        for val in values:
            out += ['#reset 1', f'#{key} {val}', texts[(i * 11 + 5) % len(texts)]]
            i += 1
    # A few combinations of setters.
    combos = [
        ['#voicing 1', '#f0style 3'],
        ['#voicing 2', '#gender 1'],
        ['#glot 6', '#f0style 4'],
        ['#gender 2', '#f0style 2', '#rate 450'],
        ['#gender 3', '#vfactor 250', '#perturb 300'],
        ['#speakmode 2', '#f0style 3'],
        ['#avbias -30', '#ahbias 20', '#afbias 20', '#voicing 1'],
        ['#pitch 2000', '#f0range 500'],
        ['#pitch 10', '#rate 20'],
    ]
    for c in combos:
        for t in (texts[i % len(texts)], texts[(i + 17) % len(texts)]):
            out += ['#reset 1'] + c + [t]
            i += 1
    out.append('#reset 1')
    out.append('#mode phon')
    out.append('#voice 0')
    out += PHON_EXTRA
    out.append('#voice 19')
    out += PHON + PHON_EXTRA
    for v in (5, 12):
        out.append(f'#voice {v}')
        out += PHON_EXTRA[v % 2::2]
    for k, v in enumerate((1, 2, 8, 9, 13, 15)):
        out.append(f'#voice {v}')
        out += PHON_EXTRA[k % 4::4]
    out.append('#voice 0')
    for k, c in enumerate((['#voicing 1'], ['#voicing 2'], ['#f0style 3'], ['#f0style 4'], ['#f0style 2'], ['#gender 3'])):
        out += ['#reset 1'] + c + PHON_EXTRA[k % 4::4]
    out.append('#reset 1')
    # Notes below the table (negative index folded up an octave at a time).
    out += [
        "{f0style sing; transpose -40; c1} LAA5 {c0} LAA5.",
        "{f0style sing; transpose -100; c1} LAA5.",
        "{f0style random; transpose -40; c1} LAA5 {c0} LAA5 LAA5.",
    ]
    out.append('#mode text')
    return out


def main():
    lines = frames_en()
    path = os.path.join(mkcorpus.CORPUS, 'frames_en.txt')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(path, sum(1 for l in lines if l and not l.startswith('#')), 'cases')


if __name__ == '__main__':
    main()
